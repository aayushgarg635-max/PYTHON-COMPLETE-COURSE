# list -ordererd ,can be changed , allows duplicates
fruits = ["apple","banana","grapes","watermelon","pineapple","apple","grapes"]

# Sets -unordered , removes duplicate elements automatically
unique_fruits = set(fruits) # duplicates apple and grapes will be removed automatically

# Tuple - ordered , cannot be changed 
box_dimensions = (5,10,25)

# RESULT 

print("List:", fruits)
