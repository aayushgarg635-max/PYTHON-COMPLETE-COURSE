# 1. LIST [brackets] - Can hold duplicates and can be changed
fruits_list = ["apple", "banana", "apple"]

# 2. TUPLE (parentheses) - Cannot be changed after creation
colors_tuple = ("red", "green", "yellow")

# 3. DICTIONARY {key: value} - Stores pairs of data
age_dict = {"Alice": 25, "Bob": 30}

# 4. SET {braces} - Automatically removes duplicate items
numbers_set = {1, 2, 2, 3}

# Printing the results
print("List:", fruits_list)
print("Tuple:", colors_tuple)
print("Dictionary:", age_dict)
print("Set:", numbers_set)  
# Notice the duplicate '2' disappears!
